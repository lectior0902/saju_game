/** 개척 포인트 n(1부터)에 해당하는 이야기 칸. 봄 기질(필요 3)은 마지막 칸을 3번째로 당겨 쓴다. */
export function stageIndex(n, need) { return need === 3 && n >= 3 ? 3 : Math.min(n, 4) - 1; }

/** 퀘스트 일지: 분야별 단계 목록과 진행 상태 */
export function questView(ch, f, need) {
  const q = QUEST[f], idxs = need === 3 ? [0, 1, 3] : [0, 1, 2, 3];
  const done = Math.min(ch.pioneer[f], need);
  return {
    title: q.title, total: need, done,
    open: ch.opened.has(f), easy: ch.route.includes(f),
    stages: idxs.map((i, k) => ({ title: q.stages[i].t, state: k < done ? "done" : k === done ? "now" : "todo", log: (ch.questLog[f] || [])[k] || null })),
  };
}
